def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)


def repeat_header(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trPr.append(el)


def TABLE(headers, rows, widths=None, size=9, first_col_bold=False):
    n = len(headers)
    if widths is None:
        widths = [USABLE / n] * n
    s = sum(widths)
    widths = [w * USABLE / s for w in widths]

    t = doc.add_table(rows=1, cols=n)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    tblPr = t._tbl.tblPr
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tblPr.append(layout)
    for i, w in enumerate(widths):
        t.columns[i].width = Cm(w)

    hdr = t.rows[0]
    repeat_header(hdr)
    for i, h in enumerate(headers):
        c = hdr.cells[i]
        c.width = Cm(widths[i])
        c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = c.paragraphs[0]
        p.paragraph_format.space_after = Pt(1)
        p.paragraph_format.space_before = Pt(1)
        write_runs(p, h, size, True)
        shade(c, "DCE6F1")

    for row in rows:
        tr = t.add_row()
        trPr = tr._tr.get_or_add_trPr()
        cant = OxmlElement("w:cantSplit")
        trPr.append(cant)
        cells = tr.cells
        for i, val in enumerate(row):
            c = cells[i]
            c.width = Cm(widths[i])
            c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            lines = str(val).split("\n")
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.line_spacing = 1.15
            write_runs(p, lines[0], size, first_col_bold and i == 0)
            for line in lines[1:]:
                p2 = c.add_paragraph()
                p2.paragraph_format.space_after = Pt(1)
                p2.paragraph_format.space_before = Pt(0)
                p2.paragraph_format.line_spacing = 1.15
                write_runs(p2, line, size, first_col_bold and i == 0)
    P("", space_after=4)
    return t


