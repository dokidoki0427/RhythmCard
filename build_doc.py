# ---------- 基础工具 ----------
def set_run(r, size=10.5, bold=False, color=None, italic=False):
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.italic = italic
    r.font.name = FONT
    rPr = r._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:eastAsia"), FONT)
    rFonts.set(qn("w:ascii"), FONT)
    rFonts.set(qn("w:hAnsi"), FONT)
    if color is not None:
        r.font.color.rgb = color
    return r


def write_runs(p, text, size=10.5, bold=False, color=None):
    """把文本写入段落，【…】占位符标红加粗。"""
    for part in TOKEN.split(text):
        if not part:
            continue
        r = p.add_run(part)
        if TOKEN.fullmatch(part):
            set_run(r, size, True, RGBColor(0xC0, 0x00, 0x00))
        else:
            set_run(r, size, bold, color)


def P(text="", size=10.5, bold=False, indent=0, space_after=6, color=None, align=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(0)
    pf.line_spacing = 1.3
    if indent:
        pf.left_indent = Cm(indent)
    if align is not None:
        p.alignment = align
    if text:
        write_runs(p, text, size, bold, color)
    return p


def BULLET(text, level=1, size=10.5):
    p = doc.add_paragraph(style="List Bullet" if level == 1 else "List Bullet 2")
    pf = p.paragraph_format
    pf.space_after = Pt(3)
    pf.line_spacing = 1.25
    write_runs(p, text, size)
    return p


